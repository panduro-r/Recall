// Run in an isolated local preview only. Reads the saved report; never uses a wallet.
export async function checkRecordedExample(){
  if(location.hostname!=="127.0.0.1")throw Error("This check is local-only.");
  const assert=(value,message)=>{if(!value)throw Error(message);};
  const $=id=>document.getElementById(id),report=(await (await fetch("/api/proof")).json());
  assert(!$("proof-content").hidden&&$("proof-error").hidden,"Saved report loaded");
  assert(document.querySelector('link[href="/workspace.css"]'),"Shared workspace design");
  assert(!document.querySelector('link[href="/style.css"]'),"No legacy plum stylesheet");
  assert(document.querySelector('.example-archive').textContent.includes("not your current purchase"),"Historical boundary visible");
  assert(!document.querySelector('a[href="/purchase"]'),"No primary link to legacy signing flow");
  assert([...document.querySelectorAll('.example-next a')].every(a=>a.getAttribute('href')==='/workspace'),"CTA returns to current product");
  const choose=id=>document.querySelector('[data-claim="'+id+'"]').click();
  choose("inference-v1");
  assert($("proof-status").textContent==="Canceled · not paid","Original cancellation preserved");
  assert($("proof-transfer").hidden&&$("proof-view-receipt").hidden,"Original has no recipient-transfer proof");
  assert($("proof-amount").textContent==="0.030test GEN","Canceled amount exact");
  assert(document.querySelectorAll('.proof-document').length===2,"Original and amendment retained");
  const originalDocs=[...document.querySelectorAll('.proof-document pre')].map(e=>e.textContent);
  assert(originalDocs[0]===report.documents['inference-v1.txt']&&originalDocs[1]===report.documents['inference-amendment.txt'],"Complete evidence unchanged");
  for(const link of document.querySelectorAll('.proof-document a'))assert(link.protocol==='https:'&&link.rel.includes('noopener'),"Pinned source safe");
  $("example-tab-terms").focus();
  $("example-tab-terms").dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowRight',bubbles:true,cancelable:true}));
  assert(document.activeElement===$("example-tab-activity")&&!$("example-panel-activity").hidden&&$("example-panel-terms").hidden,"Arrow navigation changes tab and focus");
  $("example-tab-activity").dispatchEvent(new KeyboardEvent('keydown',{key:'End',bubbles:true,cancelable:true}));
  assert(document.activeElement===$("example-tab-details")&&!$("example-panel-details").hidden,"End selects last tab");
  $("example-tab-details").dispatchEvent(new KeyboardEvent('keydown',{key:'Home',bubbles:true,cancelable:true}));
  assert(document.activeElement===$("example-tab-terms"),"Home selects first tab");
  choose("inference-replacement");
  assert(document.activeElement.dataset.claim==='inference-replacement',"Purchase selection retains focus");
  assert($("proof-status").textContent==="Paid · transfer verified","Replacement receipt verified");
  assert($("proof-amount").textContent==="0.040test GEN","Replacement amount exact");
  assert(document.querySelectorAll('.proof-document').length===1,"Replacement evidence separate");
  assert(document.querySelector('.proof-document pre').textContent===report.documents['inference-replacement.txt'],"Replacement document unchanged");
  $("proof-view-receipt").click();
  assert(!$("example-panel-activity").hidden&&!$("proof-transfer").hidden,"Receipt action opens correct tab");
  const payment=report.report.receipts.at(-1);
  assert($("proof-transfer-fields").textContent.includes(payment.hash)&&$("proof-transfer-fields").textContent.includes(payment.child.hash)&&$("proof-transfer-fields").textContent.includes(payment.child.to_address),"Exact parent, child and recipient retained");
  const receipts=[...document.querySelectorAll('.example-event pre')].map(e=>JSON.parse(e.textContent));
  assert(receipts.length===11&&JSON.stringify(receipts)===JSON.stringify(report.report.receipts),"All eleven receipts unmodified and in order");
  for(const receipt of document.querySelectorAll('.example-event'))receipt.open=true;
  assert(document.documentElement.scrollWidth<=innerWidth,"Expanded receipts do not overflow viewport");
  $("example-tab-details").click();
  assert($("proof-studio").href.endsWith(report.report.session.contract),"Historical contract not current purchase");
  choose("inference-v1");
  assert(!$("example-panel-terms").hidden&&$("proof-transfer").hidden&&$("proof-transfer-fields").children.length===0,"Switching back clears replacement proof");
  assert(document.querySelectorAll('[role="tab"][tabindex="0"]').length===1,"Exactly one roving tab stop");
  assert(document.documentElement.scrollWidth<=innerWidth,"Terms fit viewport");
  return {passed:true,receipts:receipts.length,viewport:innerWidth,selected:$("proof-title").textContent};
}
